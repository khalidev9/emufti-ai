export function getTranslation(lang: SupportedLanguage, key: string, fallback?: string): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  if (dict && dict[key]) return dict[key];
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];

  // Check alias patterns for settings tabs (e.g., settings.profile_tab vs settings.tab_profile)
  if (key.includes('_tab')) {
    const swapped = key.replace(/\.([a-z0-9_-]+)_tab$/, '.tab_$1');
    if (dict && dict[swapped]) return dict[swapped];
    if (TRANSLATIONS.en && TRANSLATIONS.en[swapped]) return TRANSLATIONS.en[swapped];
  } else if (key.includes('.tab_')) {
    const swapped = key.replace(/\.tab_([a-z0-9_-]+)$/, '.$1_tab');
    if (dict && dict[swapped]) return dict[swapped];
    if (TRANSLATIONS.en && TRANSLATIONS.en[swapped]) return TRANSLATIONS.en[swapped];
  }

  return fallback !== undefined ? fallback : key;
}
